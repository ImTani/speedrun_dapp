// Writes the standalone mask files and the contact sheet:
//   public/masks/<aspect>.svg            (gilded, 220 px, standalone)
//   public/masks/<aspect>-grisaille.svg  public/masks/<aspect>-ink.svg
//   public/masks/sheet.html              (all seven at 48 / 120 / 220 px, three variants)
// Run from apps/web:  node src/ui/masks/tools/build-sheet.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MASK } from "../../../scene/masks.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const web = path.resolve(here, "../../../..");
const OUT = path.join(web, "public/masks");

const NAMES = [
	["mercy", "Mercy", "Volto"],
	["hunger", "Hunger", "Bauta"],
	["echo", "Echo", "Colombina"],
	["rancour", "Rancour", "Pantalone"],
	["appetite", "Appetite", "Arlecchino"],
	["inquisitor", "Inquisitor", "Medico della Peste"],
	["madness", "Madness", "Jolly"],
];

const standalone = (svg) =>
	svg.replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" ');

for (const [k, name, form] of NAMES) {
	const credit = `${name} (${form}). Forms from game-icons.net, CC BY 3.0, by Lorc and Delapouite. See /ATTRIBUTION.md.`;
	fs.writeFileSync(
		path.join(OUT, `${k}.svg`),
		standalone(
			MASK.mask(k, 220, {
				variant: "gilded",
				still: true,
				fit: "square",
				title: `${name}, ${form}`,
			}),
		).replace("<defs>", `<desc>${credit}</desc><defs>`),
	);
	for (const v of ["grisaille", "ink"])
		fs.writeFileSync(
			path.join(OUT, `${k}-${v}.svg`),
			standalone(
				MASK.mask(k, 220, {
					variant: v,
					still: true,
					fit: "square",
					title: `${name}, ${form}`,
				}),
			).replace("<defs>", `<desc>${credit}</desc><defs>`),
		);
}

const row = (variant, glow) =>
	NAMES.map(
		([k, name, form]) => `<figure>
	<div class="sizes">
		<span class="chip">${MASK.mask(k, 48, { variant, glow, void: !glow, fit: "square" })}</span>
		${MASK.mask(k, 120, { variant, glow, void: !glow, fit: "square" })}
		${MASK.mask(k, 220, { variant, glow, void: !glow, fit: "square" })}
	</div>
	<figcaption><b>${name}</b> <i>${form}</i></figcaption>
</figure>`,
	).join("\n");

const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>Aspect masks, contact sheet</title>
<meta name="viewport" content="width=device-width,initial-scale=1">
<style>
	body{margin:0;padding:24px;background:radial-gradient(120% 80% at 50% 0%,#1d1418 0%,#0b0807 70%);color:#e9dcc1;font:14px/1.4 Georgia,serif}
	h1{font:600 22px Georgia,serif;letter-spacing:.06em;margin:0 0 4px}
	h2{font:600 15px Georgia,serif;letter-spacing:.12em;text-transform:uppercase;color:#c9a24e;margin:28px 0 10px;border-bottom:1px solid #c9a24e33;padding-bottom:6px}
	p{margin:0;color:#a8977c}
	.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:14px}
	figure{margin:0;padding:12px;background:#0006;border:1px solid #ffffff10;border-radius:4px}
	.sizes{display:flex;align-items:center;gap:14px}
	.chip{display:inline-flex;width:56px;height:56px;align-items:center;justify-content:center;background:#0008;border:2px solid #c9a24e55}
	figcaption{margin-top:6px}figcaption i{color:#a8977c}
	.paper{background:#e9dcc1;color:#1a1210}
	.paper figure{background:#d9c9a8}
</style></head><body>
<h1>Aspect masks</h1>
<p>Forms: game-icons.net (CC BY 3.0, Lorc and Delapouite), re-fitted and restyled as one set. Generated by src/ui/masks/tools/build-sheet.mjs.</p>
<h2>Gilded, ember eyes</h2><div class="grid">${row("gilded", true)}</div>
<h2>Gilded</h2><div class="grid">${row("gilded", false)}</div>
<h2>Grisaille (glass painting)</h2><div class="grid">${row("grisaille", false)}</div>
<h2>Ink</h2><div class="grid">${row("ink", false)}</div>
</body></html>
`;
fs.writeFileSync(path.join(OUT, "sheet.html"), html);
console.log("wrote public/masks/*.svg and sheet.html");
