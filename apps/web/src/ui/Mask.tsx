"use client";

import { useReducedMotion } from "motion/react";
import { type CSSProperties, useEffect, useId, useMemo, useRef } from "react";
import { L } from "@/lexicon";
import { registerEmitter } from "@/scene/emitters.js";
import { MASK, type MaskVariant } from "@/scene/masks.js";

export type { MaskVariant };

export interface MaskProps {
	/** Aspect index 0..6 (Mercy, Hunger, Echo, Rancour, Appetite, Inquisitor, Madness). */
	aspect: number;
	/** Box size in px. With fit "square" (default) the mask is size x size. */
	size?: number;
	/** Older name for size. */
	width?: number;
	/** Ember eyes burning behind the eye holes. */
	glow?: boolean;
	/**
	 * The ember eyes light the scene (with glow): registered as emitters, so an Atmosphere
	 * mounted in the same scene adds their hot bloom and a faint red spill around the mask.
	 * For masks standing in a scene (the Gathering face-off), not UI chips.
	 */
	emit?: boolean;
	/** gilded (full colour), grisaille (brown glass painting) or ink (paper and ink). */
	variant?: MaskVariant;
	/** "square": framed tightly on the mask (default). "space": the shared 100 x 84 mask space. */
	fit?: "square" | "space";
	/** Speak the mask's name to screen readers (otherwise it is decorative). */
	label?: boolean;
	/** Lift the mask off the page with a soft shadow (default true). */
	shadow?: boolean;
	className?: string;
	style?: CSSProperties;
}

/** An Aspect mask (index 0-6), drawn from the shared mask set (src/scene/masks.js). */
export function Mask({
	aspect,
	size,
	width,
	glow = false,
	emit = false,
	variant = "gilded",
	fit = "square",
	label = false,
	shadow = true,
	className,
	style,
}: MaskProps) {
	const a = L.aspects[aspect] ?? L.aspects[0];
	const px = size ?? width ?? 60;
	const reduced = useReducedMotion() ?? false;
	const uid = useId();
	const svg = useMemo(
		() =>
			MASK.mask(a.key, px, {
				variant,
				glow,
				still: reduced,
				void: !glow,
				fit,
				id: `k${uid}`,
				title: label ? `${a.name}, ${a.mask}` : undefined,
			}),
		[a, px, variant, glow, reduced, fit, uid, label],
	);
	const ref = useRef<HTMLSpanElement>(null);
	// biome-ignore lint/correctness/useExhaustiveDependencies: svg is the markup the eyes sit in
	useEffect(() => {
		const el = ref.current?.querySelector("svg");
		if (!emit || !glow || !el) return;
		const vb = el.viewBox.baseVal;
		if (!vb?.width || !vb.height) return;
		const eyes = MASK.EYES[a.key as keyof typeof MASK.EYES] ?? [];
		const hs = eyes.map(([x, y], i) =>
			registerEmitter({
				kind: "ember",
				anchor: el,
				x: (x - vb.x) / vb.width,
				y: (y - vb.y) / vb.height,
				// the eye's glow, in mask widths (the spill reaches about twice this)
				radius: 9 / vb.width,
				color: "#e2481e",
				intensity: 0.9,
				phase: (aspect * 0.17 + i * 0.41) % 1,
			}),
		);
		return () => {
			for (const h of hs) h.remove();
		};
	}, [emit, glow, svg, a.key, aspect]);
	return (
		<span
			ref={ref}
			className={className ? `mask-svg ${className}` : "mask-svg"}
			style={{
				lineHeight: 0,
				filter: shadow ? "drop-shadow(0 3px 4px rgb(0 0 0 / .55))" : undefined,
				...style,
			}}
			// biome-ignore lint/security/noDangerouslySetInnerHtml: static SVG markup generated by our own mask module
			dangerouslySetInnerHTML={{ __html: svg }}
		/>
	);
}
