const font = (
	role: string,
	def: string,
	prefer: FontKind[],
	label = "Face",
): TuneControl => ({
	kind: "font",
	key: `${role}-font`,
	label,
	def,
	weightKey: `${role}-weight`,
	prefer,
});
const weight = (role: string, def: number): TuneControl => ({
	kind: "weight",
	key: `${role}-weight`,
	label: "Weight",
	def,
	fontKey: `${role}-font`,
});
const range = (
	key: string,
	label: string,
	def: number,
	min: number,
	max: number,
	step: number,
	unit?: "em",
): TuneControl => ({
	kind: "range",
	key,
	label,
	def,
	min,
	max,
	step,
	...(unit ? { unit, suffix: " em" } : {}),
});
const scale = (role: string, min = 0.6, max = 1.6): TuneControl => ({
	kind: "range",
	key: `${role}-size`,
	label: "Size",
	def: 1,
	min,
	max,
	step: 0.01,
	suffix: "x",
});
const tracking = (
	role: string,
	def: number,
	min = -0.04,
	max = 0.3,
): TuneControl =>
	range(`${role}-tracking`, "Tracking", def, min, max, 0.005, "em");
const color = (
	key: string,
	label: string,
	def: string,
	also?: string[],
): TuneControl => ({
	kind: "color",
	key,
	label,
	def,
	...(also ? { also } : {}),
});
const letterCase = (role: string, def: CaseMode): TuneControl => ({
	kind: "case",
	key: `${role}-case`,
	label: "Case",
	def,
});
const style = (role: string, def: StyleMode): TuneControl => ({
	kind: "style",
	key: `${role}-style`,
	label: "Style",
	def,
});

