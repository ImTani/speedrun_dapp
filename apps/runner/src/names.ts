export function houseName(index: number): string {
	const base = NAMES[index % NAMES.length] as string;
	const lap = Math.floor(index / NAMES.length);
	return lap === 0
		? base
		: `${base} ${["II", "III", "IV", "V", "VI"][lap - 1] ?? lap + 1}`;
}
